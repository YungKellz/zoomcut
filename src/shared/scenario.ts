const PUNCTUATION_VK: Record<number, string> = {
  0xba: ';', 0xbb: '=', 0xbc: ',', 0xbd: '-', 0xbe: '.', 0xbf: '/',
  0xc0: '`', 0xdb: '[', 0xdc: '\\', 0xdd: ']', 0xde: "'"
}

function baseKeyLabel(e: { scan: number; vk: number; extended: boolean }): string {
  const named = KEY_NAMES[`${e.scan}:${e.extended}`]
  if (named) return named
  if (e.vk >= 48 && e.vk <= 57) return String.fromCharCode(e.vk) // 0-9
  if (e.vk >= 65 && e.vk <= 90) return String.fromCharCode(e.vk) // A-Z
  if (PUNCTUATION_VK[e.vk]) return PUNCTUATION_VK[e.vk]
  return `Key${e.scan}`
}

function describeKeyLabel(e: RawKeyEvent): string {
  const parts: string[] = []
  if (e.mods.ctrl) parts.push('Ctrl')
  if (e.mods.shift) parts.push('Shift')
  if (e.mods.alt) parts.push('Alt')
  if (e.mods.meta) parts.push('Win')
  parts.push(baseKeyLabel(e))
  return parts.join('+')
}

